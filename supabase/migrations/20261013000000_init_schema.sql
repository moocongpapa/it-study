-- Invoker views preserve the underlying progress RLS and give the dashboard
-- explicit aggregate/status contracts without duplicating mutable state.
create or replace view public.user_progress with (security_invoker = true) as
select me.user_id,
  count(t.id)::integer as total_topics,
  count(p.topic_id) filter (where p.is_completed)::integer as completed_topics,
  count(p.topic_id) filter (where not p.is_completed)::integer as started_topics,
  min(p.next_review_at) filter (where p.next_review_at is not null) as next_review_at
from (select (select auth.uid()) as user_id) me
cross join public.topics t
left join public.user_node_progress p
  on p.user_id = me.user_id and p.topic_id = t.id
where me.user_id is not null
group by me.user_id;

create or replace view public.user_node_status with (security_invoker = true) as
select me.user_id, t.id as topic_id, t.slug, p.current_level,
  coalesce(p.is_completed, false) as is_completed,
  unmet.unmet_prerequisites,
  case
    when coalesce(p.is_completed, false) then 'completed'
    when unmet.unmet_prerequisites > 0 then 'locked'
    when p.topic_id is not null then 'in_progress'
    else 'available'
  end as status
from (select (select auth.uid()) as user_id) me
cross join public.topics t
left join public.user_node_progress p
  on p.user_id = me.user_id and p.topic_id = t.id
cross join lateral (
  select count(*)::integer as unmet_prerequisites
  from public.topic_prerequisites edge
  where edge.to_topic_id = t.id
    and not exists (
      select 1 from public.user_node_progress completed
      where completed.user_id = me.user_id
        and completed.topic_id = edge.from_topic_id
        and completed.is_completed
    )
) unmet
where me.user_id is not null;

revoke all on public.user_progress, public.user_node_status from public, anon, authenticated;
grant select on public.user_progress, public.user_node_status to authenticated;
grant select on public.user_progress, public.user_node_status to service_role;

commit;
