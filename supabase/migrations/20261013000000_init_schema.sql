begin;

create schema if not exists curriculum_internal;

do $$
begin
  if not exists (
    select 1 from pg_type t
    join pg_namespace n on n.oid = t.typnamespace
    where n.nspname = 'public' and t.typname = 'topic_difficulty'
  ) then
    create type public.topic_difficulty as enum
      ('beginner', 'intermediate', 'advanced', 'expert');
  end if;
end $$;

create table if not exists public.domains (
  id uuid primary key default gen_random_uuid(),
  slug text not null unique check (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
  title text not null check (length(btrim(title)) > 0),
  description text not null default '',
  icon_name text not null,
  display_order integer not null unique check (display_order > 0),
  created_at timestamptz not null default now()
);

create table if not exists public.topics (
  id uuid primary key default gen_random_uuid(),
  domain_id uuid not null references public.domains(id) on delete cascade,
  slug text not null unique check (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
  title text not null check (length(btrim(title)) > 0),
  summary text not null default '',
  difficulty public.topic_difficulty not null,
  estimated_minutes integer not null check (estimated_minutes between 1 and 10080),
  display_order integer not null check (display_order > 0),
  created_at timestamptz not null default now(),
  unique (domain_id, display_order)
);

create table if not exists public.topic_prerequisites (
  id bigint generated by default as identity primary key,
  from_topic_id uuid not null references public.topics(id) on delete cascade,
  to_topic_id uuid not null references public.topics(id) on delete cascade,
  created_at timestamptz not null default now(),
  constraint topic_prerequisites_not_self check (from_topic_id <> to_topic_id),
  constraint topic_prerequisites_unique_edge unique (from_topic_id, to_topic_id)
);

create table if not exists public.articles (
  id uuid primary key default gen_random_uuid(),
  topic_id uuid not null unique references public.topics(id) on delete cascade,
  level_1_mental_model text,
  level_2_core_engineering text,
  level_3_troubleshooting text,
  level_4_architecture_tradeoffs text,
  is_published boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint published_articles_have_all_levels check (
    not is_published or (
      nullif(btrim(level_1_mental_model), '') is not null and
      nullif(btrim(level_2_core_engineering), '') is not null and
      nullif(btrim(level_3_troubleshooting), '') is not null and
      nullif(btrim(level_4_architecture_tradeoffs), '') is not null
    )
  )
);

create table if not exists public.quizzes (
  id uuid primary key default gen_random_uuid(),
  topic_id uuid not null references public.topics(id) on delete cascade,
  level smallint not null check (level between 1 and 4),
  question text not null check (length(btrim(question)) > 0),
  choices jsonb not null,
  answer_index smallint not null,
  explanation text not null,
  created_at timestamptz not null default now(),
  unique (topic_id, level, question),
  constraint quizzes_valid_choices check (
    case when jsonb_typeof(choices) = 'array'
      then jsonb_array_length(choices) between 2 and 6
        and answer_index >= 0
        and answer_index < jsonb_array_length(choices)
      else false
    end
  )
);

create table if not exists public.user_node_progress (
  user_id uuid not null references auth.users(id) on delete cascade,
  topic_id uuid not null references public.topics(id) on delete cascade,
  is_completed boolean not null default false,
  current_level smallint not null default 1 check (current_level between 1 and 4),
  self_assessment smallint check (self_assessment between 1 and 5),
  completed_at timestamptz,
  last_reviewed_at timestamptz,
  next_review_at timestamptz,
  review_interval_days integer not null default 0 check (review_interval_days >= 0),
  ease_factor numeric(3,2) not null default 2.50 check (ease_factor between 1.30 and 9.99),
  review_count integer not null default 0 check (review_count >= 0),
  updated_at timestamptz not null default now(),
  primary key (user_id, topic_id),
  constraint completion_consistency check (
    (is_completed and current_level = 4 and completed_at is not null)
    or (not is_completed and completed_at is null)
  )
);

-- A single writer lock prevents concurrent transactions from introducing a cycle.
-- The recursive UNION also terminates if legacy data already contains a cycle.
create or replace function curriculum_internal.enforce_topic_dag()
returns trigger
language plpgsql
security invoker
set search_path = pg_catalog, public
as $$
begin
  perform pg_advisory_xact_lock(hashtextextended('public.topic_prerequisites.dag', 0));
  if exists (
    with recursive reachable(topic_id) as (
      select p.to_topic_id
      from public.topic_prerequisites p
      where p.from_topic_id = new.to_topic_id
        and (tg_op <> 'UPDATE' or p.id <> new.id)
      union
      select p.to_topic_id
      from public.topic_prerequisites p
      join reachable r on r.topic_id = p.from_topic_id
      where (tg_op <> 'UPDATE' or p.id <> new.id)
    )
    select 1 from reachable where topic_id = new.from_topic_id
  ) then
    raise exception 'Prerequisite edge would create a cycle: % -> %',
      new.from_topic_id, new.to_topic_id using errcode = '23514';
  end if;
  return new;
end;
$$;

drop trigger if exists topic_prerequisites_dag_guard on public.topic_prerequisites;
create trigger topic_prerequisites_dag_guard
before insert or update of from_topic_id, to_topic_id
on public.topic_prerequisites
for each row execute function curriculum_internal.enforce_topic_dag();

create or replace function curriculum_internal.touch_updated_at()
returns trigger
language plpgsql
security invoker
set search_path = pg_catalog
as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

drop trigger if exists articles_touch_updated_at on public.articles;
create trigger articles_touch_updated_at
before update on public.articles
for each row execute function curriculum_internal.touch_updated_at();
drop trigger if exists progress_touch_updated_at on public.user_node_progress;
create trigger progress_touch_updated_at
before update on public.user_node_progress
for each row execute function curriculum_internal.touch_updated_at();

